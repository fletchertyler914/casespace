#!/usr/bin/env node
/**
 * Validates report-templates.json and emits Rust template ID constants.
 * Run: node scripts/codegen-report-templates.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const jsonPath = path.join(root, "packages/types/report-templates.json");
const outPath = path.join(
  root,
  "apps/desktop-backend/src-tauri/src/report_templates.generated.rs",
);

const templates = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
if (!Array.isArray(templates) || templates.length === 0) {
  console.error("report-templates.json must be a non-empty array");
  process.exit(1);
}

const ids = templates.map((t) => t.id);
const unique = new Set(ids);
if (unique.size !== ids.length) {
  console.error("Duplicate template ids in report-templates.json");
  process.exit(1);
}

const rust = `// @generated by scripts/codegen-report-templates.mjs — do not edit
//! Template identifiers synced from packages/types/report-templates.json

pub const TEMPLATE_IDS: &[&str] = &[
${ids.map((id) => `    "${id}",`).join("\n")}
];

pub fn is_known_template(id: &str) -> bool {
    TEMPLATE_IDS.contains(&id)
}
`;

fs.writeFileSync(outPath, rust);
console.log(`Wrote ${outPath} (${ids.length} templates)`);
